# ==================== 信息提取提示词 ====================

EXTRACTION_PROMPT = """请从以下对话历史中提取用户的关键信息。

## 对话历史
{conversations}

## 要求提取的信息
1. 用户的名字（如果提到）
2. 用户的兴趣爱好
3. 用户的重要事实（如职业、所在地、近期计划等）
4. 用户的偏好（如喜欢/不喜欢的事物）

## 输出格式
请用 JSON 格式输出，只输出 JSON，不要其他内容：
{{
    "name": "用户名字或null",
    "interests": ["兴趣1", "兴趣2"],
    "facts": ["事实1", "事实2"],
    "preferences": {{"喜欢的事物": "...", "不喜欢的事物": "..."}}
}}

如果没有发现任何有价值的信息，返回空的 JSON：
{{"name": null, "interests": [], "facts": [], "preferences": {{}}}}
"""


